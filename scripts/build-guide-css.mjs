/**
 * Scopes a design-system bundle's stylesheet so it can live inside this site.
 *
 *     node scripts/build-guide-css.mjs prosomnus
 *     node scripts/build-guide-css.mjs oc-fellows
 *
 * Every one of these bundles ships the same two hazards: its tokens are
 * declared on `:root`, and its stylesheet is written for a standalone page.
 * Dropped in as-is the tokens collide with the site's own variables and rules
 * like `body{}` restyle the page around the guide. This re-homes the tokens
 * onto a scope class and prefixes every selector with it, so a guide can only
 * ever style itself.
 *
 * Run again if a bundle under `public/design-systems/` is replaced. Output is
 * committed, so nothing parses CSS at build time.
 */
import fs from 'node:fs'
import path from 'node:path'

const BUNDLES = {
  prosomnus: {
    scope: '.psguide',
    tokens: ['fonts', 'colors', 'typography', 'spacing', 'motion'],
    // This bundle's guide styles live inline in its brand-guide page.
    inlineFrom: 'brand-guide/index.html',
    out: 'src/app/(frontend)/design-systems/prosomnus/_guide/guide.css',
    // It was a full-viewport app; here it sits in a panel that owns its height.
    replace: [[/(\.psguide \.app\{[^}]*?)height:\s*100vh;/, '$1height: 100%;']],
  },
  'oc-fellows': {
    scope: '.ocfguide',
    tokens: ['fonts', 'colors', 'typography', 'spacing', 'radius', 'elevation', 'motion', 'base'],
    // This one has no assembled guide page — only token files.
    inlineFrom: null,
    out: 'src/app/(frontend)/design-systems/oc-fellows/_guide/guide.css',
    replace: [],
  },
}

const name = process.argv[2]
const cfg = BUNDLES[name]
if (!cfg) {
  console.error(`unknown bundle "${name}". known: ${Object.keys(BUNDLES).join(', ')}`)
  process.exit(1)
}

const SRC = path.join('public', 'design-systems', name)
const { scope: SCOPE } = cfg

/**
 * Rules that would reach outside the guide if kept. `:root` is NOT here: it
 * carries the tokens and is re-homed onto the scope class instead of dropped.
 */
const ESCAPES = /^(html|body|\*)\b/
const stripComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '')
/** URL-aware: a Google Fonts URL contains `;`, so consume `url(...)` whole. */
const IMPORT = /@import\s+url\([^()]*\)\s*;/g

/** Walks top-level blocks, tracking brace depth so nested at-rules stay intact. */
function* blocks(css) {
  let i = 0
  while (i < css.length) {
    const open = css.indexOf('{', i)
    if (open === -1) return
    const selector = css.slice(i, open).trim()
    let depth = 0
    let j = open
    for (; j < css.length; j++) {
      if (css[j] === '{') depth++
      else if (css[j] === '}' && --depth === 0) break
    }
    yield { selector, body: css.slice(open + 1, j) }
    i = j + 1
  }
}

const scopeSelector = (sel) =>
  sel
    .split(',')
    .map((p) => p.trim())
    .filter((p) => p && !ESCAPES.test(p))
    // `:root` BECOMES the scope (no descendant space) so the custom properties
    // land on the guide's own element; everything else is nested under it.
    .map((p) => (p === ':root' || p === 'html:root' ? SCOPE : `${SCOPE} ${p}`))
    .join(', ')

function scope(css) {
  const out = []
  for (const { selector, body } of blocks(css)) {
    if (selector.startsWith('@keyframes') || selector.startsWith('@font-face')) {
      out.push(`${selector}{${body}}`) // inner blocks are frames, not selectors
    } else if (selector.startsWith('@')) {
      const inner = []
      for (const b of blocks(body)) {
        const s = scopeSelector(b.selector)
        if (s) inner.push(`${s}{${b.body}}`)
      }
      out.push(`${selector}{${inner.join('')}}`)
    } else {
      const s = scopeSelector(selector)
      if (s) out.push(`${s}{${body}}`)
    }
  }
  return out.join('\n')
}

const imports = []
const tokens = cfg.tokens.map((t) => {
  let css = stripComments(fs.readFileSync(path.join(SRC, 'tokens', `${t}.css`), 'utf8'))
  imports.push(...(css.match(IMPORT) ?? []))
  css = css.replace(IMPORT, '')
  // Every token file goes through the same scoper — some carry base element
  // rules alongside the custom properties (base.css does), and guessing which
  // is what by regex is how `:root` ended up scoped twice.
  return `/* tokens/${t}.css */\n${scope(css)}`
})

let guide = ''
if (cfg.inlineFrom) {
  const html = fs.readFileSync(path.join(SRC, cfg.inlineFrom), 'utf8')
  guide = scope(stripComments(/<style>([\s\S]*?)<\/style>/.exec(html)[1]))
  for (const [from, to] of cfg.replace) guide = guide.replace(from, to)
}

fs.mkdirSync(path.dirname(cfg.out), { recursive: true })
fs.writeFileSync(
  cfg.out,
  [
    `/* GENERATED by scripts/build-guide-css.mjs ${name} — do not hand-edit. */`,
    [...new Set(imports)].join('\n'), // @import must lead the file
    '',
    `/* ---- design tokens, re-homed from :root onto ${SCOPE} ---- */`,
    tokens.join('\n\n'),
    guide ? `\n/* ---- guide layout, scoped from ${cfg.inlineFrom} ---- */\n${guide}` : '',
    '',
  ].join('\n'),
)

const written = fs.readFileSync(cfg.out, 'utf8')
const balanced = (written.match(/\{/g) ?? []).length === (written.match(/\}/g) ?? []).length
console.log(`wrote ${cfg.out} — ${written.length} chars, braces ${balanced ? 'balanced' : 'MISMATCHED'}`)
if (!balanced) process.exit(1)
